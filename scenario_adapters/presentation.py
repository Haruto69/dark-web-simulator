RANSOMWARE_VOCABULARY = Vocabulary(RANSOMWARE_STATE_SENTENCES,
                                   RANSOMWARE_DISPLAY_ORDER,
                                   RANSOMWARE_NEGATIVE_WORTH_SHOWING,
                                   RANSOMWARE_FORMATTERS)


def choice_labels_for(scenario_key):
    """One scenario's ``choice_id -> label`` map, or an empty map.

    An unknown scenario key resolves to no vocabulary at all rather than to
    another scenario's, so a caller can never accidentally render a label that
    belongs to a different scenario.
    """
    source = CHOICE_LABEL_SOURCES.get(scenario_key)
    return dict(source()) if source is not None else {}


def label_for_choice(scenario_key, choice_id):
    """The display label for one scenario's choice id.

    Falls back to the choice id itself -- an intentionally neutral rendering --
    when the scenario key is unknown or the id is not one of that scenario's
    choices. It never searches another scenario's vocabulary.
    """
    return choice_labels_for(scenario_key).get(choice_id, choice_id or "")
